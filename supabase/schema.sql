-- Offentlig påmelding. All kontroll skjer her, ikke bare i nettleseren.
-- Er personen allerede påmeldt i gruppen, skjer det ingenting (og ingen får vite det).
drop function if exists public.register_member(uuid, text, int, text, text, boolean);
create or replace function public.register_member(
  p_group       uuid,
  p_full_name   text,
  p_birth_year  int,
  p_gender      text,
  p_postal_code text,
  p_city        text,
  p_consent     boolean
)
returns json
language plpgsql security definer set search_path = public
as $$
declare
  v_group public.groups%rowtype;
  v_name  text := public.norm_name(p_full_name);
  v_pc    text := public.norm_space(p_postal_code);
  v_city  text := public.norm_name(p_city);
begin
  select * into v_group from public.groups where id = p_group and active;
  if not found then
    raise exception 'Fant ikke gruppen. Be lederen om en ny lenke.';
  end if;
  if p_consent is not true then
    raise exception 'Du må samtykke for å melde deg på.';
  end if;
  if v_name is null or char_length(v_name) < 3 or v_name !~ '[[:alpha:]]' or position(' ' in v_name) = 0 then
    raise exception 'Skriv fullt navn (fornavn og etternavn).';
  end if;
  if char_length(v_name) > 100 then
    raise exception 'Navnet er for langt.';
  end if;
  if p_birth_year is null or p_birth_year < 1900 or p_birth_year > extract(year from now())::int then
    raise exception 'Skriv et gyldig fødselsår.';
  end if;
  if lower(coalesce(p_gender, '')) not in ('mann', 'kvinne') then
    raise exception 'Velg kjønn.';
  end if;
  if v_pc is null or v_pc !~ '^[0-9]{4}$' then
    raise exception 'Postnummer må være fire siffer.';
  end if;
  if not exists (select 1 from public.postal_codes where code = v_pc) and (select count(*) from public.postal_codes) > 0 then
    raise exception 'Fant ikke postnummeret. Sjekk at det er riktig.';
  end if;
  if (select count(*) from public.postal_codes) = 0 and (v_city is null or char_length(v_city) < 2) then
    raise exception 'Skriv inn sted.';
  end if;
  -- Enkel bremse mot misbruk
  if (select count(*) from public.members where created_at > now() - interval '1 hour') > 200 then
    raise exception 'Mange påmeldinger akkurat nå. Prøv igjen om litt.';
  end if;

  insert into public.members (group_id, full_name, birth_year, gender, postal_code, city, consent)
  values (p_group, v_name, p_birth_year, lower(p_gender), v_pc, coalesce(v_city, 'Ukjent'), true)
  on conflict do nothing;

  return json_build_object('group_name', v_group.name);
end;
$$;

-- Lagre oppmøte (lager samlingen hvis den ikke finnes, og erstatter listen).
-- Starttid, timer og type: tomt betyr «som forrige samling» (eller 19:00, 2 timer, Fysisk).
drop function if exists public.save_attendance(uuid, date, uuid[]);
create or replace function public.save_attendance(
  p_group      uuid,
  p_date       date,
  p_member_ids uuid[],
  p_start      time    default null,
  p_hours      numeric default null,
  p_mode       text    default null
)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_id    uuid;
  v_start time;
  v_hours numeric;
  v_mode  text;
begin
  if auth.uid() is null or not (public.is_admin() or public.leads_group(p_group)) then
    raise exception 'Du har ikke tilgang til denne gruppen';
  end if;
  if p_hours is not null and (p_hours <= 0 or p_hours > 12) then
    raise exception 'Antall timer må være mellom 0,5 og 12.';
  end if;
  if p_mode is not null and p_mode not in ('Fysisk', 'Digitalt') then
    raise exception 'Velg Fysisk eller Digitalt.';
  end if;
  if p_date > (now() at time zone 'Europe/Oslo')::date then
    raise exception 'Samlingen har ikke vært ennå. Oppmøte kan registreres fra samme dag.';
  end if;
  select m.start_time, m.hours, m.mode into v_start, v_hours, v_mode
  from public.meetings m
  where m.group_id = p_group and exists (select 1 from public.attendance a where a.meeting_id = m.id)
  order by m.meeting_date desc limit 1;

  insert into public.meetings (group_id, meeting_date, start_time, hours, mode)
  values (p_group, p_date,
          coalesce(p_start, v_start, '19:00'),
          coalesce(round(p_hours * 2) / 2, v_hours, 2),
          coalesce(p_mode, v_mode, 'Fysisk'))
  on conflict (group_id, meeting_date) do update
    set start_time = coalesce(p_start, public.meetings.start_time),
        hours      = coalesce(round(p_hours * 2) / 2, public.meetings.hours),
        mode       = coalesce(p_mode, public.meetings.mode)
  returning id into v_id;

  delete from public.attendance where meeting_id = v_id;
  insert into public.attendance (meeting_id, member_id)
  select v_id, m.id from public.members m
  where m.group_id = p_group and m.archived_at is null and m.id = any(coalesce(p_member_ids, '{}'));
  return v_id;
end;
$$;

-- Ukentlige samlinger: hver aktive gruppe får en samling hver onsdag (kl. 19–21 som standard),
-- fra første onsdag etter at gruppen ble laget og til og med i dag. Kalles når noen åpner siden.
-- En samling uten registrert oppmøte er «tom»: den vises i historikken, men ikke i eksport/statistikk.
create or replace function public.ensure_weekly_meetings()
returns int
language plpgsql security definer set search_path = public
as $$
declare
  v_today date := (now() at time zone 'Europe/Oslo')::date;
  n int;
begin
  if auth.uid() is null then
    raise exception 'Du må være logget inn';
  end if;
  insert into public.meetings (group_id, meeting_date, start_time, hours, mode)
  select g.id, w.d,
         coalesce(last.start_time, '19:00'), coalesce(last.hours, 2), coalesce(last.mode, 'Fysisk')
  from public.groups g
  cross join lateral (
    select greatest((g.created_at at time zone 'Europe/Oslo')::date, v_today - 730) as start
  ) s
  cross join lateral (
    select (gs)::date as d
    from generate_series((s.start + ((10 - extract(isodow from s.start)::int) % 7))::timestamp, v_today::timestamp, interval '7 days') gs
  ) w
  left join lateral (
    select m.start_time, m.hours, m.mode from public.meetings m
    where m.group_id = g.id and exists (select 1 from public.attendance a where a.meeting_id = m.id)
    order by m.meeting_date desc limit 1
  ) last on true
  where g.active and (public.is_admin() or public.leads_group(g.id))
  on conflict (group_id, meeting_date) do nothing;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- Felles kontroll av en ny leder (brukes av invitasjoner)
create or replace function public.check_invitee(p_name text, p_email text, p_phone text)
returns void
language plpgsql immutable set search_path = public
as $$
begin
  if public.norm_name(p_name) is null or char_length(public.norm_name(p_name)) < 2 then
    raise exception 'Skriv navnet på personen.';
  end if;
  if public.norm_email(p_email) is null or public.norm_email(p_email) !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    raise exception 'Skriv inn en gyldig e-postadresse.';
  end if;
  if public.norm_phone(p_phone) is null or public.norm_phone(p_phone) !~ '^\+[0-9]{8,15}$' then
    raise exception 'Skriv inn et gyldig telefonnummer.';
  end if;
end;
$$;

-- Lag invitasjon til leder eller nestleder. E-post og telefon er påkrevd.
-- En ny invitasjon til samme e-post i samme gruppe erstatter den gamle.
drop function if exists public.create_invite(uuid, text, text);
create or replace function public.create_invite(
  p_group     uuid,
  p_role      text default 'leder',
  p_name      text default null,
  p_email     text default null,
  p_phone     text default null,
  p_member_id uuid default null
)
returns text
language plpgsql security definer set search_path = public
as $$
declare
  v_code text := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
begin
  if auth.uid() is null or not (public.is_admin() or public.leads_group(p_group)) then
    raise exception 'Du har ikke tilgang til denne gruppen';
  end if;
  if p_role not in ('leder', 'nestleder') then
    raise exception 'Ugyldig rolle';
  end if;
  perform public.check_invitee(p_name, p_email, p_phone);
  if exists (select 1 from public.group_leaders gl join public.profiles p on p.id = gl.user_id
             where gl.group_id = p_group and p.email = public.norm_email(p_email)) then
    raise exception 'Personen er allerede leder i denne gruppen.';
  end if;
  -- Én leder per gruppe. En ny leder får en egen gruppe (create_group).
  if p_role = 'leder' and (
       exists (select 1 from public.group_leaders where group_id = p_group and role = 'leder')
    or exists (select 1 from public.group_invites where group_id = p_group and role = 'leder' and used_at is null
               and email is distinct from public.norm_email(p_email))) then
    raise exception 'Gruppen har allerede en leder. En ny leder får sin egen smågruppe.';
  end if;
  delete from public.group_invites
  where group_id = p_group and used_at is null and email = public.norm_email(p_email);
  insert into public.group_invites (code, group_id, role, name, email, phone, member_id, created_by)
  values (v_code, p_group, p_role, p_name, p_email, p_phone, p_member_id, auth.uid());
  return v_code;
end;
$$;

