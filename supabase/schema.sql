-- Lagre triade (admin). Bare personer som leder en gruppe kan være med.
create or replace function public.save_triad(p_id uuid, p_name text, p_members uuid[])
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_id uuid := p_id;
begin
  if not public.is_admin() then
    raise exception 'Bare administratorer kan sette sammen triader';
  end if;
  if coalesce(array_length(p_members, 1), 0) < 2 then
    raise exception 'En triade må ha minst to ledere';
  end if;
  if array_length(p_members, 1) > 3 then
    raise exception 'En triade kan ha maks tre ledere';
  end if;
  if (select count(distinct u) from unnest(p_members) u) <> array_length(p_members, 1) then
    raise exception 'Samme person er valgt flere ganger';
  end if;
  if exists (select 1 from unnest(p_members) u
             where not exists (select 1 from public.group_leaders gl where gl.user_id = u and gl.role = 'leder')) then
    raise exception 'Bare smågruppeledere kan være i en triade, ikke nestledere';
  end if;
  if v_id is null then
    insert into public.triads (name) values (public.norm_space(p_name)) returning id into v_id;
  else
    update public.triads set name = public.norm_space(p_name) where id = v_id;
    if not found then raise exception 'Fant ikke triaden'; end if;
    delete from public.triad_members where triad_id = v_id;
  end if;
  delete from public.triad_members where user_id = any(p_members);
  insert into public.triad_members (triad_id, user_id) select v_id, u from unnest(p_members) u;
  delete from public.triads t where not exists (select 1 from public.triad_members m where m.triad_id = t.id);
  return v_id;
end;
$$;

-- Oversikt per gruppe for admin (siste samling og snitt oppmøte siste 90 dager)
drop function if exists public.admin_overview();
create or replace function public.admin_overview()
returns table (group_id uuid, last_meeting date, meetings_90 int, avg_present_90 numeric)
language plpgsql stable security definer set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Bare for administratorer';
  end if;
  return query
  select g.id,
         (select max(m.meeting_date) from public.meetings m where m.group_id = g.id
            and exists (select 1 from public.attendance a where a.meeting_id = m.id)),
         (select count(*)::int from public.meetings m where m.group_id = g.id and m.meeting_date > current_date - 90
            and exists (select 1 from public.attendance a where a.meeting_id = m.id)),
         (select round(avg(c), 1) from (
            select (select count(*) from public.attendance a where a.meeting_id = m.id) c
            from public.meetings m where m.group_id = g.id and m.meeting_date > current_date - 90) x
          where c > 0)
  from public.groups g;
end;
$$;

