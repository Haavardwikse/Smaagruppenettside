-- En leder som kobles til en deltaker, må koble til en deltaker i samme gruppe
create or replace function public.trg_check_member_group()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if new.member_id is not null and not exists (
    select 1 from public.members where id = new.member_id and group_id = new.group_id) then
    raise exception 'Personen er ikke med i denne gruppen';
  end if;
  return new;
end;
$$;

