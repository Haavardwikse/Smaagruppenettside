-- Fjerner mellomrom i start og slutt og slår sammen doble mellomrom
create or replace function public.norm_space(p text)
returns text
language sql immutable set search_path = public
as $$
  select nullif(btrim(regexp_replace(coalesce(p, ''), '\s+', ' ', 'g')), '');
$$;

-- Navn: rydder mellomrom. Er alt skrevet med små eller store bokstaver,
-- får hvert ord stor forbokstav ("kari NORDMANN" blir ikke rørt, "kari nordmann" → "Kari Nordmann").
create or replace function public.norm_name(p text)
returns text
language sql immutable set search_path = public
as $$
  select case
    when public.norm_space(p) is null then null
    when public.norm_space(p) = lower(public.norm_space(p))
      or public.norm_space(p) = upper(public.norm_space(p))
      then initcap(public.norm_space(p))
    else public.norm_space(p)
  end;
$$;

-- Telefon: lagres alltid som +landskode og sifre. 8 sifre regnes som norsk (+47).
create or replace function public.norm_phone(p text)
returns text
language plpgsql immutable set search_path = public
as $$
declare
  d text := regexp_replace(coalesce(p, ''), '[^0-9+]', '', 'g');
begin
  if d = '' then return null; end if;
  if d like '00%' then d := '+' || substr(d, 3); end if;
  if d ~ '^[0-9]{8}$' then return '+47' || d; end if;
  if d ~ '^47[0-9]{8}$' then return '+' || d; end if;
  return d;
end;
$$;

-- E-post: små bokstaver uten mellomrom
create or replace function public.norm_email(p text)
returns text
language sql immutable set search_path = public
as $$
  select nullif(lower(btrim(coalesce(p, ''))), '');
$$;


