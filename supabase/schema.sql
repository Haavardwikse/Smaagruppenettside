-- Deltakere: ryddige navn, riktig poststed, fødselsår ikke fram i tid
create or replace function public.trg_members_clean()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_city text;
begin
  new.full_name   := public.norm_name(new.full_name);
  new.postal_code := public.norm_space(new.postal_code);
  new.city        := public.norm_name(new.city);
  if new.postal_code is not null then
    select city into v_city from public.postal_codes where code = new.postal_code;
    if v_city is not null then new.city := v_city; end if;
  end if;
  if new.birth_year is not null and new.birth_year > extract(year from now())::int then
    raise exception 'Fødselsåret kan ikke være fram i tid';
  end if;
  new.gender := lower(public.norm_space(new.gender));
  if tg_op = 'INSERT' and new.gender is null then
    raise exception 'Velg kjønn.';
  end if;
  return new;
end;
$$;

drop trigger if exists members_clean on public.members;
create trigger members_clean
  before insert or update of full_name, postal_code, city, birth_year, gender on public.members
  for each row execute function public.trg_members_clean();

