create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

create or replace function public.leads_group(gid uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.group_leaders where group_id = gid and user_id = auth.uid());
$$;

create or replace function public.in_my_triad(p_user uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.triad_members a
    join public.triad_members b on a.triad_id = b.triad_id
    where a.user_id = auth.uid() and b.user_id = p_user);
$$;

-- Ledes gruppen av noen i min triade?
create or replace function public.is_triad_group(gid uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.group_leaders gl
    where gl.group_id = gid and public.in_my_triad(gl.user_id));
$$;


