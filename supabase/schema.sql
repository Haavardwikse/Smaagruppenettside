$$;

-- Godta invitasjon. Kontoen må ha samme e-post som invitasjonen.
create or replace function public.accept_invite(p_code text)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v public.group_invites%rowtype;
  v_email text;
  v_group uuid;
begin
  if auth.uid() is null then
    raise exception 'Du må være logget inn';
  end if;
  select * into v from public.group_invites where code = p_code for update;
  if not found or v.used_at is not null or v.expires_at < now() then
    raise exception 'Invitasjonen er ugyldig, utløpt eller allerede brukt';
  end if;
  select email into v_email from public.profiles where id = auth.uid();
  if v.email is not null and v_email is distinct from v.email then
    raise exception 'Invitasjonen gjelder %. Logg inn eller lag konto med den e-posten.', v.email;
  end if;

  if v.role = 'admin' then
    update public.group_invites set used_by = auth.uid(), used_at = now() where code = p_code;
    update public.profiles
    set role      = 'admin',
        full_name = case when coalesce(full_name, '') = '' then coalesce(v.name, full_name) else full_name end,
        phone     = coalesce(phone, v.phone)
    where id = auth.uid();
    return null;
  end if;

  v_group := v.group_id;
  -- Én leder per gruppe: har gruppen fått en annen leder i mellomtiden, får denne lederen en ny gruppe
  if v.role = 'leder' and exists (select 1 from public.group_leaders
      where group_id = v.group_id and role = 'leder' and user_id <> auth.uid()) then
    insert into public.groups (name)
    values (left(coalesce(public.norm_name(v.name), split_part(v_email, '@', 1)), 80))
    returning id into v_group;
  end if;

  insert into public.group_leaders (group_id, user_id, role, member_id)
  values (v_group, auth.uid(), v.role, case when v_group = v.group_id then v.member_id end)
  on conflict (group_id, user_id) do update
    set role = excluded.role,
        member_id = coalesce(excluded.member_id, public.group_leaders.member_id);

  update public.group_invites set used_by = auth.uid(), used_at = now() where code = p_code;
  update public.profiles
  set full_name = case when coalesce(full_name, '') = '' then coalesce(v.name, full_name) else full_name end,
      phone     = coalesce(phone, v.phone)
  where id = auth.uid();
  return v_group;
end;
$$;

